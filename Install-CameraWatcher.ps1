<#
.SYNOPSIS
    Installs (or removes) the camera import watcher as a per-user startup item.

.DESCRIPTION
    Registering a Scheduled Task needs elevation on this machine, so the watcher
    is installed as a .vbs launcher in the user's Startup folder instead.
    VBScript rather than a shortcut because WScript.Shell.Run can start the
    process with no window at all -- a .lnk to powershell.exe flashes a console.

    Installing also starts the watcher immediately, so there is no need to log
    out, and it removes the older Canon-only startup item if one is present.

.EXAMPLE
    .\Install-CameraWatcher.ps1
    .\Install-CameraWatcher.ps1 -Eject
    .\Install-CameraWatcher.ps1 -Uninstall
#>
[CmdletBinding()]
param(
    [string] $CanonRoot = (Join-Path $env:USERPROFILE 'CameraImports\Canon'),
    [string] $GoProRoot = (Join-Path $env:USERPROFILE 'CameraImports\GoPro'),
    [switch] $KeepOriginals,
    [switch] $KeepProxies,
    [switch] $FlatGroups,
    [switch] $Eject,
    [switch] $Uninstall
)

$ErrorActionPreference = 'Stop'

$startup = [Environment]::GetFolderPath('Startup')
$vbsPath = Join-Path $startup 'CameraPhotoImport.vbs'
$oldVbs = Join-Path $startup 'CanonPhotoImport.vbs'
$watcher = Join-Path $PSScriptRoot 'Watch-CameraDrives.ps1'

function Get-WatcherProcess {
    <#
        Match only processes actually launched as "-File ...Watch-*Drives.ps1",
        and never this process. Matching a bare script name against the whole
        command line also matches any shell that merely mentions it -- including
        the one running this installer -- which would kill the user's own window.
    #>
    Get-CimInstance Win32_Process -Filter "Name = 'powershell.exe'" -ErrorAction SilentlyContinue |
    Where-Object {
        $_.ProcessId -ne $PID -and $_.CommandLine -and
        $_.CommandLine -match '-File\s+"?[^"]*Watch-(Camera|Canon)Drives\.ps1"?'
    }
}

function Stop-Watcher {
    $stopped = 0
    foreach ($p in @(Get-WatcherProcess)) {
        Stop-Process -Id $p.ProcessId -Force -ErrorAction SilentlyContinue
        $stopped++
    }
    return $stopped
}

if ($Uninstall) {
    foreach ($p in @($vbsPath, $oldVbs)) {
        if (Test-Path -LiteralPath $p) {
            Remove-Item -LiteralPath $p -Force
            Write-Host "Removed $p" -ForegroundColor Green
        }
    }
    Write-Host "Stopped $(Stop-Watcher) running watcher process(es)." -ForegroundColor Green
    return
}

if (-not (Test-Path -LiteralPath $watcher)) { throw "Cannot find $watcher" }

# Retire the Canon-only watcher this tool replaces.
if (Test-Path -LiteralPath $oldVbs) {
    Remove-Item -LiteralPath $oldVbs -Force
    Write-Host "Removed superseded startup item: $oldVbs" -ForegroundColor Yellow
}

$psArgs = '-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "{0}" -CanonRoot "{1}" -GoProRoot "{2}"' -f `
    $watcher, $CanonRoot.TrimEnd('\'), $GoProRoot.TrimEnd('\')
if ($KeepOriginals) { $psArgs += ' -KeepOriginals' }
if ($KeepProxies) { $psArgs += ' -KeepProxies' }
if ($FlatGroups) { $psArgs += ' -FlatGroups' }
if ($Eject) { $psArgs += ' -Eject' }

# In VBScript a literal double quote inside a string is written as two quotes.
$vbsLiteral = ('powershell.exe ' + $psArgs).Replace('"', '""')

$vbs = @"
' Starts the camera media import watcher with no visible window.
' Generated by Install-CameraWatcher.ps1 -- edit that script, not this file.
Set sh = CreateObject("WScript.Shell")
sh.Run "$vbsLiteral", 0, False
"@

Set-Content -LiteralPath $vbsPath -Value $vbs -Encoding ascii
Write-Host "Installed startup item: $vbsPath" -ForegroundColor Green

$n = Stop-Watcher
if ($n -gt 0) { Write-Host "Stopped $n previous watcher process(es)."; Start-Sleep -Seconds 1 }

Start-Process -FilePath 'wscript.exe' -ArgumentList "`"$vbsPath`"" -WindowStyle Hidden
Start-Sleep -Seconds 2

$running = @(Get-WatcherProcess)

if ($running.Count -gt 0) {
    Write-Host "Watcher running (PID $($running[0].ProcessId))." -ForegroundColor Green
}
else {
    Write-Host 'Watcher did not start -- check the log.' -ForegroundColor Red
}
Write-Host "Canon -> $CanonRoot"
Write-Host "GoPro -> $GoProRoot"
Write-Host "Log   -> $(Join-Path $env:LOCALAPPDATA 'CameraImport\import.log')"
